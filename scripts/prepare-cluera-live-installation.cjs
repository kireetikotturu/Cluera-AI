'use strict';
// Transactional, default-off installation. No credentials, provider requests,
// profile provisioning or bank promotion. Any preservation failure rolls back.
const {prepare:schema}=require('./prepare-cluera-live-schema.cjs');
function prepare(){return `-- Generated by scripts/prepare-cluera-live-installation.cjs. Install once.
begin;
set local lock_timeout='2s';
set local statement_timeout='60s';
select pg_advisory_xact_lock(862117,20261021);
do $$declare r record;begin
 if to_regnamespace('cluera_live_billing_private')is not null or to_regnamespace('cluera_billing_runtime_private')is not null
 or to_regprocedure('public.cluera_billing_native_history(uuid,uuid,text,bigint)')is null
 then raise exception 'Live installation precondition requires review';end if;
 -- Stable ordering and short timeout; no concurrent usage/financial writes can
 -- cross the snapshot. Contention fails the entire transaction, never retries.
 for r in select n.nspname,c.relname from pg_class c join pg_namespace n on n.oid=c.relnamespace
 where n.nspname in('public','billing_private','cluera_billing_private','cluera_private')and c.relkind='r' order by n.nspname,c.relname loop
 execute format('lock table %I.%I in share row exclusive mode',r.nspname,r.relname);
 end loop;
 if exists(select 1 from public.customer_usage_runs where state='ACTIVE')
 or exists(select 1 from public.customer_usage_windows w left join public.customer_usage_settlements s using(user_id,run_id,sequence)where s.user_id is null)
 then raise exception 'Usage must drain before Live schema installation';end if;
end$$;
create temporary table cluera_live_install_rows(schema_name text,table_name text,row_count bigint,digest text)on commit drop;
do $$declare r record;n bigint;h text;begin
 for r in select ns.nspname schema_name,c.relname table_name from pg_class c join pg_namespace ns on ns.oid=c.relnamespace
 where ns.nspname in('public','billing_private','cluera_billing_private','cluera_private')and c.relkind='r'loop
 execute format('select count(*),md5(coalesce(string_agg(to_jsonb(t)::text,''|''order by to_jsonb(t)::text),''''))from %I.%I t',r.schema_name,r.table_name)into n,h;
 insert into cluera_live_install_rows values(r.schema_name,r.table_name,n,h);
 end loop;
end$$;
create temporary table cluera_live_install_functions on commit drop as
 select ns.nspname schema_name,p.proname,pg_get_function_identity_arguments(p.oid)args,p.prosrc,p.proconfig,p.prosecdef,p.provolatile
 from pg_proc p join pg_namespace ns on ns.oid=p.pronamespace where ns.nspname in('public','billing_private','cluera_billing_private','cluera_private');
${schema().replace(/^begin;$/m,'').replace(/^commit;$/m,'')}
do $$declare r record;n bigint;h text;target_name text;actual_source text;projection text;begin
 for r in select *from cluera_live_install_rows loop
 projection:=case when r.schema_name='public'and r.table_name='customer_usage_grants'then '(to_jsonb(t)-''billing_mode'')'else 'to_jsonb(t)'end;
 execute format('select count(*),md5(coalesce(string_agg(%s::text,''|''order by %s::text),''''))from %I.%I t',projection,projection,r.schema_name,r.table_name)into n,h;
 if n<>r.row_count or h<>r.digest then raise exception 'Existing business rows changed during Live installation';end if;
 end loop;
 for r in select *from cluera_live_install_functions loop
 target_name:=case when r.schema_name='public'and r.proname in('cluera_billing_prepare','customer_usage_command','customer_usage_balance','cluera_credits_read')then r.proname||'_pre_modes'else r.proname end;
 select p.prosrc into actual_source from pg_proc p join pg_namespace ns on ns.oid=p.pronamespace
 where ns.nspname=r.schema_name and p.proname=target_name and pg_get_function_identity_arguments(p.oid)=r.args
 and p.proconfig is not distinct from r.proconfig and p.prosecdef=r.prosecdef and p.provolatile=r.provolatile;
 -- Only the three reviewed base implementations gain bank predicates. Reverse
 -- precisely those predicates to prove every previous behavior was retained.
 if r.schema_name='public'and r.proname in('customer_usage_command_base','customer_usage_balance_base','customer_credits_read_paddle_base')then
 actual_source:=replace(actual_source,'g.billing_mode not in(''shared'',cluera_billing_runtime_private.bank()) or ','');
 actual_source:=replace(actual_source,'billing_mode in(''shared'',cluera_billing_runtime_private.bank()) and ','');
 actual_source:=replace(actual_source,' and billing_mode in(''shared'',cluera_billing_runtime_private.bank())','');
 end if;
 if actual_source is distinct from r.prosrc then raise exception 'Existing function implementation was not preserved: %.%',r.schema_name,r.proname;end if;
 end loop;
 if(select count(*)from cluera_billing_runtime_private.active_bank where mode='test')<>1
 or(select count(*)from cluera_billing_runtime_private.live_profile where account_digest is null and origin is null and acceptance_digest is null and not intake_enabled and not checkout_enabled)<>1
 or exists(select 1 from cluera_billing_runtime_private.configuration_audit)
 or exists(select 1 from cluera_live_billing_private.native_config where enabled)
 or exists(select 1 from cluera_live_billing_private.catalog_heads where enabled)
 or exists(select 1 from cluera_live_billing_private.processing_owner where owner<>'account'or account_digest is not null)
 then raise exception 'Live installation activated configuration';end if;
 for r in select c.relname from pg_class c join pg_namespace ns on ns.oid=c.relnamespace
 where ns.nspname='cluera_live_billing_private'and c.relkind='r'and c.relname not in('catalog_revisions','catalog_heads','processing_owner','native_config')loop
 execute format('select count(*)from cluera_live_billing_private.%I',r.relname)into n;
 if n<>0 then raise exception 'Live financial state was created';end if;
 end loop;
 if exists(select 1 from public.customer_usage_grants where billing_mode='live')then raise exception 'Unexpected Live grant provenance';end if;
 if exists(select 1 from pg_class c join pg_namespace ns on ns.oid=c.relnamespace
 where ns.nspname in('cluera_live_billing_private','cluera_billing_runtime_private')and c.relkind='r'and(not c.relrowsecurity
 or has_table_privilege('anon',c.oid,'SELECT,INSERT,UPDATE,DELETE,TRUNCATE')or has_table_privilege('authenticated',c.oid,'SELECT,INSERT,UPDATE,DELETE,TRUNCATE')
 or has_table_privilege('service_role',c.oid,'SELECT,INSERT,UPDATE,DELETE,TRUNCATE')))
 then raise exception 'Live table privileges failed';end if;
 if exists(select 1 from pg_proc p join pg_namespace ns on ns.oid=p.pronamespace
 where(ns.nspname in('cluera_live_billing_private','cluera_billing_runtime_private')or ns.nspname='public'and p.proname like 'cluera_live_billing_%')
 and(has_function_privilege('anon',p.oid,'EXECUTE')or has_function_privilege('authenticated',p.oid,'EXECUTE')))
 then raise exception 'Live function privileges failed';end if;
end$$;
commit;
`;}
module.exports={prepare};
if(require.main===module)process.stdout.write(prepare());

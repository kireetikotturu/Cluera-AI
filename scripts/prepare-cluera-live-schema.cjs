'use strict';
// Reuse the reviewed financial algorithms in a distinct namespace. This is a
// source generator, never an application/runtime SQL executor. The generated
// proposal must pass cross-mode PostgreSQL tests before installation.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=name=>fs.readFileSync(path.join(root,'docs/proposals',name),'utf8');
function definition(sql,name){
 const pattern=new RegExp('^create (?:or replace )?function '+name.replaceAll('.','\\.')+'\\(','m');
 const start=sql.search(pattern);if(start<0)throw Error('Missing reviewed definition: '+name);
 const body=sql.indexOf('$$',start),end=sql.indexOf('$$;',body+2);
 if(body<0||end<0)throw Error('Invalid reviewed definition: '+name);
 return sql.slice(start,end+3);
}
// Remove only complete EXISTS subqueries against legacy Test/Paddle tables.
// Parentheses inside strings and nested SQL are tracked; unmatched input fails.
function withoutLegacyChecks(sql){
 const starts=[...sql.matchAll(/\bexists\s*\(/gi)].map(x=>x.index);
 for(const start of starts.reverse()){
  let end=sql.indexOf('(',start),depth=0,quoted=false;
  for(;end<sql.length;end++){
   const c=sql[end];
   if(c==="'"){if(quoted&&sql[end+1]==="'"){end++;continue;}quoted=!quoted;}
   if(quoted)continue;
   if(c==='(')depth++;
   if(c===')'&&--depth===0)break;
  }
  if(depth||quoted)throw Error('Unbalanced reviewed SQL.');
  const part=sql.slice(start,end+1);
  if(/\b(?:billing_private\.|public\.customer_(?:recurring_terms|recurring_subscriptions|billing_jobs|billing_outbox|checkout_intents|pack_purchases))/.test(part))
   sql=sql.slice(0,start)+'false'+sql.slice(end+1);
 }
 return sql;
}
function isolate(sql){
 return withoutLegacyChecks(sql)
  .replaceAll('cluera_billing_private','cluera_live_billing_private')
  .replaceAll('cluera_billing_','cluera_live_billing_')
  .replaceAll('cluera_live_live_billing_private','cluera_live_billing_private')
  .replaceAll('razorpay-test','razorpay-live');
}
function prepare(){
 const core=read('cluera-billing.sql');
 const prefix=core.slice(core.indexOf('create schema'),core.indexOf('create function public.cluera_billing_worker_nonce'));
 const names=['public.cluera_billing_worker_nonce','cluera_billing_private.refresh','cluera_billing_private.owns',
  'public.cluera_billing_owner','public.cluera_billing_cutover','public.cluera_billing_catalog','public.cluera_billing_admin_read',
  'public.cluera_billing_admin_mutate','public.cluera_billing_plan_verify','public.cluera_billing_apply',
  'public.cluera_billing_prepare','public.cluera_billing_bind','public.cluera_billing_binding'];
 let base=prefix+'\n'+names.map(name=>definition(core,name)).join('\n');
 base=base.replace("return public.account_payment_binding(p_resource,p_account_digest)||jsonb_build_object('legacy',true)",
  "return jsonb_build_object('code','UNBOUND')");
 let result='-- GENERATED by scripts/prepare-cluera-live-schema.cjs. UNAPPLIED; no Live activation.\nbegin;\n'
  +isolate(base)+'\n'+read('cluera-live-inbox.sql')+'\n';
 for(const name of ['cluera-billing-history.sql','cluera-subscription-cancellation.sql','cluera-native-recurring.sql','cluera-native-recurring-refresh.sql','cluera-native-recurring-history.sql','cluera-admin-financial-report.sql'])
  result+=isolate(read(name).replace(/^begin;$/m,'').replace(/^commit;$/m,''))+'\n';
 if(/\bbilling_private\.|\bcluera_billing_private\.|public\.account_payment_|razorpay-test/.test(result))
  throw Error('Live proposal still references a Test financial path.');
 result+=read('cluera-billing-mode-bank.sql')+'\n'+usageBankDefinitions()+'\n'+read('cluera-billing-mode-readers.sql')+'\n';
 result+=`revoke all on all functions in schema cluera_live_billing_private from public,anon,authenticated,service_role;
do $$declare f record;begin
 for f in select p.oid::regprocedure signature from pg_proc p join pg_namespace n on n.oid=p.pronamespace
 where n.nspname='public'and p.proname like 'cluera_live_billing_%'and p.proname not like '%_pre_native'and p.proname not like '%_pre_modes'loop
 execute format('revoke all on function %s from public,anon,authenticated',f.signature);
 execute format('grant execute on function %s to service_role',f.signature);end loop;
end$$;
commit;
`;
 // There is no legacy callback, inbox, catalog, grant provenance or RPC fallback.
 return result;
}
function replaceOnce(sql,from,to){if(sql.split(from).length!==2)throw Error('Usage definition changed; explicit review required.');return sql.replace(from,to);}
function usageBankDefinitions(){
 const source=fs.readFileSync(path.join(root,'supabase/migrations/20261004064105_shared_usage_reservations.sql'),'utf8');
 let command=definition(source,'public.customer_usage_command')
  .replace('create function public.customer_usage_command(','create or replace function public.customer_usage_command_base(');
 command=replaceOnce(command,"if g.state<>'ACTIVE' or","if g.billing_mode not in('shared',cluera_billing_runtime_private.bank()) or g.state<>'ACTIVE' or");
 command=replaceOnce(command,"where user_id=p_user_id and state='ACTIVE' and starts_at<=t",
  "where user_id=p_user_id and billing_mode in('shared',cluera_billing_runtime_private.bank()) and state='ACTIVE' and starts_at<=t");
 let balance=definition(source,'public.customer_usage_balance')
  .replace('create function public.customer_usage_balance(','create or replace function public.customer_usage_balance_base(');
 balance=replaceOnce(balance,'into result from public.customer_usage_grants where user_id=p_user_id;',
  "into result from public.customer_usage_grants where user_id=p_user_id and billing_mode in('shared',cluera_billing_runtime_private.bank());");
 const creditsSource=fs.readFileSync(path.join(root,'supabase/migrations/20261011014422_account_checkout_unresolved_bound_guard.sql'),'utf8');
 let credits=definition(creditsSource,'public.customer_credits_read')
  .replace('create or replace function public.customer_credits_read(','create or replace function public.customer_credits_read_paddle_base(');
 credits=replaceOnce(credits,"where user_id=p_user and state='ACTIVE' and starts_at<=t",
  "where user_id=p_user and billing_mode in('shared',cluera_billing_runtime_private.bank()) and state='ACTIVE' and starts_at<=t");
 return [command,balance,credits].join('\n');
}
module.exports={prepare,definition,withoutLegacyChecks};
if(require.main===module)process.stdout.write(prepare());

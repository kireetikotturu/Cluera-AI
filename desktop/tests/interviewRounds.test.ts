import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { Database } from '../src/main/database/Database';
import { Repositories } from '../src/main/database/Repositories';
import { SessionService } from '../src/main/app/SessionService';
import { DocumentProcessor } from '../src/main/documents/DocumentProcessor';
import { LocalRetriever } from '../src/main/retrieval/LocalRetriever';
import { ContextBuilder } from '../src/main/context/ContextBuilder';
import type { QuestionIntent, SessionInput } from '../src/shared/types';

const input: SessionInput = { title: 'Rounds', company: 'Acme', role: 'Engineer', interviewType: 'mixed', language: 'English', answerStyle: 'Natural', answerLength: 'short', resumeText: 'React experience', jobDescription: 'API engineer', instructions: '', selectedModel: 'mock', saveTranscript: true };
const question: QuestionIntent = { question: 'Explain the quasar retrieval pipeline', intent: 'TECHNICAL_QUESTION', confidence: .9, isAnswerNeeded: true, isComplete: true, requiresMoreContext: false };
describe('local interview rounds', () => {
  let dir: string, db: Database, repo: Repositories, retriever: LocalRetriever, service: SessionService;
  const connect = () => { repo = new Repositories(db); retriever = new LocalRetriever(repo, { chunkSize: 850, chunkOverlap: 120, topK: 5 }); service = new SessionService(repo, new DocumentProcessor(), retriever); };
  beforeEach(async () => { dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sigmaround-rounds-')); db = new Database(path.join(dir, 'test.sqlite')); await db.initialize(); connect(); });
  afterEach(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  it('reuses parent documents, isolates rounds, retrieves earlier evidence and keeps chronology', () => {
    const session = service.save(input), other = service.save({ ...input, title: 'Other' });
    service.addText(session.id, 'supporting', 'Context', 'Own project supporting context');
    const documents = repo.listDocuments(session.id).map(d => d.id);
    const first = repo.addTurn(session.id, 'candidate', 'My quasar retrieval pipeline uses lexical scoring and bounded context.');
    const q = repo.addQuestion(session.id, question); repo.addAnswer(session.id, q.id, '**Lexical scoring** selects relevant chunks.', 'mock', 10);
    expect(repo.hasCompletedAnswerForQuestion(session.id, question.question)).toBe(true);
    repo.addTurn(other.id, 'candidate', 'quasar OTHER-CUSTOMER-PRIVATE'); service.finishRound(other.id);
    service.startRound(session.id, 'Second technical round: retrieval');
    const second = repo.currentRound(session.id)!;
    expect(second).toMatchObject({ number: 2, note: 'Second technical round: retrieval' });
    expect(repo.contextTurns(session.id)).toEqual([]);
    expect(repo.hasCompletedAnswerForQuestion(session.id, question.question)).toBe(false);
    expect(repo.listDocuments(session.id).filter(d => d.type !== 'round-context').map(d => d.id)).toEqual(documents);
    const context = new ContextBuilder(repo, retriever).build(session, question);
    expect(context.instructions).toContain(second.note);
    expect(context.documentContext.some(c => c.documentType === 'round-context' && c.text.includes('lexical scoring'))).toBe(true);
    expect(JSON.stringify(context)).not.toContain('OTHER-CUSTOMER-PRIVATE');
    expect(context.documentContext.length).toBeLessThanOrEqual(5);
    const turn = repo.addTurn(session.id, 'candidate', 'Round two answer'); expect(turn.roundId).toBe(second.id);
    service.startRound(session.id, 'HR');
    expect(repo.listRounds(session.id).map(r => r.number)).toEqual([3, 2, 1]);
    expect(repo.roundHistory(session.id, first.roundId!).conversation[0].text).toContain('quasar');
    expect(repo.roundHistory(session.id, second.id).conversation.map(t => t.text)).toEqual(['Round two answer']);
    expect(() => repo.roundHistory(other.id, second.id)).toThrow('Round not found');
    expect(repo.getDetail(session.id)!.documents).toHaveLength(documents.length);
    expect(repo.listRounds(session.id)[1].endedAt).not.toBeNull();
  });
  it('migrates 1.0.7 records to Round 1 idempotently without losing documents or answers', async () => {
    const session = service.save(input); const turn = repo.addTurn(session.id, 'interviewer', 'Legacy transcript');
    const q = repo.addQuestion(session.id, question); repo.addAnswer(session.id, q.id, 'Legacy answer', 'mock', 5);
    const sql = db.connection();
    sql.run("UPDATE sessions SET created_at='2020-01-01T00:00:00.000Z'");
    sql.run('DROP INDEX idx_turns_round; DROP INDEX idx_questions_round; ALTER TABLE conversation_turns DROP COLUMN round_id; ALTER TABLE questions DROP COLUMN round_id; DROP TABLE interview_rounds;');
    db.close(); await db.initialize(); connect();
    const first = repo.listRounds(session.id)[0];
    expect(first).toMatchObject({ number: 1, state: 'completed' });
    expect(first.startedAt).toBe(turn.createdAt);
    expect(repo.roundHistory(session.id, first.id)).toMatchObject({ conversation: [{ id: turn.id }], questions: [{ id: q.id, answer: { text: 'Legacy answer' } }] });
    expect(repo.listDocuments(session.id)).toHaveLength(2);
    db.close(); await db.initialize(); connect(); expect(repo.listRounds(session.id)).toHaveLength(1);
    service.startRound(session.id); expect(repo.currentRound(session.id)?.number).toBe(2);
  });
  it('recovers an interrupted round and does not persist unrecorded speech in summaries', async () => {
    const session = service.save({ ...input, saveTranscript: false });
    const first = repo.addTurn(session.id, 'candidate', 'DO-NOT-PERSIST-SPEECH');
    const q = repo.addQuestion(session.id, question); repo.addAnswer(session.id, q.id, 'Saved submitted answer', 'mock', 5);
    db.close(); await db.initialize(); connect();
    expect(repo.listRounds(session.id)[0].state).toBe('interrupted');
    service.startRound(session.id);
    expect(repo.currentRound(session.id)?.number).toBe(2);
    expect(repo.roundHistory(session.id, first.roundId!).conversation).toEqual([]);
    expect(JSON.stringify(repo.listDocuments(session.id))).not.toContain('DO-NOT-PERSIST-SPEECH');
    expect(repo.listDocuments(session.id).some(d => d.text.includes('Saved submitted answer'))).toBe(true);
  });
  it('retries indexing without duplicate context documents and rejects invalid notes before ending a round', () => {
    const session = service.save(input); repo.addTurn(session.id, 'candidate', 'Recorded evidence');
    const index = vi.spyOn(retriever, 'index').mockImplementationOnce(() => { throw new Error('Synthetic indexing failure'); });
    expect(() => service.finishRound(session.id)).toThrow('Synthetic');
    expect(repo.currentRound(session.id)).toBeNull();
    index.mockRestore(); service.startRound(session.id);
    expect(repo.listDocuments(session.id).filter(d => d.type === 'round-context')).toHaveLength(1);
    expect(() => service.startRound(session.id, 'x'.repeat(2001))).toThrow('2,000');
    expect(repo.currentRound(session.id)?.number).toBe(2);
  });
  it('bounds pages and cleans up all round data with the parent session', () => {
    const session = service.save(input);
    for (let i = 0; i < 105; i++) repo.addTurn(session.id, 'candidate', `Turn ${i}`);
    const round = repo.currentRound(session.id)!; service.finishRound(session.id);
    expect(repo.roundHistory(session.id, round.id, 0)).toMatchObject({ hasMore: true });
    expect(repo.roundHistory(session.id, round.id, 0).conversation).toHaveLength(100);
    expect(repo.roundHistory(session.id, round.id, 1).conversation).toHaveLength(5);
    repo.deleteSession(session.id);
    for (const table of ['interview_rounds', 'conversation_turns', 'questions', 'answers', 'documents', 'document_chunks']) expect(db.all(`SELECT * FROM ${table}`)).toEqual([]);
  });
});
